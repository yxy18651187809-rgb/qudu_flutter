def add_edu_goal(filepath):
    """为单个L5文件添加教育目标章节"""
    fname = os.path.basename(filepath)
    
    # 提取编号
    num_match = re.search(r'L5-(\d+)', fname)
    if not num_match:
        return f"SKIP: {fname} - 无法提取编号"
    
    num = f"L5-{num_match.group(1)}"
    if num not in EDU_GOALS:
        return f"SKIP: {fname} - 无教育目标数据"
    
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 检查是否已有教育目标
    if re.search(r'##\s*四[、．]\s*教育目标', content):
        return f"SKIP: {fname} - 已有教育目标"
    
    # 构建教育目标章节
    goals = EDU_GOALS[num]
    section = f"""## 四、教育目标

### 1. 识字目标
{goals['识字']}

### 2. 认知目标
{goals['认知']}

### 3. 情感目标
{goals['情感']}

### 4. 能力目标
{goals['能力']}

"""
    
    # 找到插入位置：在"五、配套练习"之前
    # 先找三、故事正文的结束位置，然后找五、配套练习的位置
    match5 = re.search(r'\n##\s*五[、．]\s*配套练习', content)
    if match5:
        # 在五、配套练习之前插入
        insert_pos = match5.start()
        new_content = content[:insert_pos] + '\n' + section + content[insert_pos:]
    else:
        # 没有五、配套练习，尝试在故事正文末尾之后插入
        match3_end = re.search(r'##\s*三[、．]\s*故事正文.*?(?=\n##|\Z)', content, re.DOTALL)
        if match3_end:
            insert_pos = match3_end.end()
            new_content = content[:insert_pos] + '\n' + section + content[insert_pos:]
        else:
            return f"FAIL: {fname} - 找不到插入位置"
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(new_content)
    
    return f"OK: {fname} - 已添加教育目标"


# 主执行
files = sorted([f for f in os.listdir(CONTENT_DIR) if f.startswith('L5-') and f.endswith('.md')])
results = {"OK": 0, "SKIP": 0, "FAIL": 0}

for fname in files:
    filepath = os.path.join(CONTENT_DIR, fname)
    result = add_edu_goal(filepath)
    print(f"  {result}")
    
    if result.startswith("OK"):
        results["OK"] += 1
    elif result.startswith("SKIP"):
        results["SKIP"] += 1
    else:
        results["FAIL"] += 1

print(f"\n完成：{results['OK']} 添加 / {results['SKIP']} 跳过 / {results['FAIL']} 失败")
