function getRadical(char) {
  return RADICALS[char] || '一';
}

/**
 * 获取汉字结构（简化估算）
 */
function getStructure(strokeCount) {
  if (strokeCount <= 4) return '独体';
  if (strokeCount <= 8) return '左右';
  if (strokeCount <= 12) return '上下';
  return '左右'; // 多数复杂字为左右结构
}

/**
 * 等级到年级的映射
 */
function levelToGrade(level) {
  switch (level) {
    case 3: return 2;
    case 4: return 3;
    case 5: return 4;
    default: return level - 1;
  }
}

/**
 * 导入单个级别的字库数据
 */
async function seedLevel(level) {
  const fileName = `L${level}完整字_后端导入.json`;
  const jsonPath = path.join(__dirname, `../../../01-内容/${fileName}`);

  if (!fs.existsSync(jsonPath)) {
    console.log(`[Seed-L${level}] ⚠️ 未找到字表: ${jsonPath}`);
    return 0;
  }

  const rawData = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));

  // L1/L2 是数组格式，L3/L4/L5 是对象格式
  let characters;
  if (Array.isArray(rawData)) {
    // L2 格式：已经是完整的Character格式
    characters = rawData;
  } else {
    // L3/L4/L5 格式：{ level, totalChars, uniqueChars, duplicateChars, characters: [...] }
    characters = rawData.characters || [];
  }

  // 过滤：只导入新字（isReview=false 或 无此字段的L2数据）
  const newChars = characters.filter(c => {
    if (c.isReview !== undefined) return c.isReview === false;
    return true; // L2格式没有isReview字段，全部导入
  });

  console.log(`[Seed-L${level}] JSON文件: ${fileName}`);
  console.log(`[Seed-L${level}] 总字数: ${characters.length}, 新字: ${newChars.length}, 复习字(跳过): ${characters.length - newChars.length}`);

  // 清理旧数据
  await Character.deleteMany({ level });
  console.log(`[Seed-L${level}] 已清理 L${level} Character 数据`);

  // 转换为Character model格式
  const docs = newChars.map(item => {
    // L2 格式已有完整字段
    if (item.strokeCount) {
      return {
        character: item.character,
        unicode: item.unicode || generateUnicode(item.character),
        pinyin: item.pinyin,
        tone: item.tone || extractTone(item.pinyin),
        strokeCount: item.strokeCount,
        radical: item.radical || '',
        structure: item.structure || getStructure(item.strokeCount),
        level,
        grade: item.grade || levelToGrade(level),
        coreLevel: item.coreLevel === '核心' || item.coreLevel === 'core' || item.isCore ? 'core' : 'extended',
        frequency: item.frequency || 0,
        etymology: item.etymology || undefined,
        meanings: item.meanings || [],
        imageUrl: item.imageUrl || '',
        animationUrl: item.animationUrl || '',
        status: 'active'
      };
    }

    // L3/L4/L5 简化格式：需要补全字段
    const strokeCount = getStrokeCount(item.character);
    return {
      character: item.character,
      unicode: generateUnicode(item.character),
      pinyin: item.pinyin,
      tone: extractTone(item.pinyin),
      strokeCount,
      radical: getRadical(item.character),
      structure: getStructure(strokeCount),
      level,
      grade: levelToGrade(level),
      coreLevel: item.isCore ? 'core' : 'extended',
      frequency: 0,
      etymology: undefined,
      meanings: [],
      imageUrl: '',
      animationUrl: '',
      status: 'active'
    };
  });

  // 批量插入，跳过已存在的字符（同一字符可能已从低级别导入）
  let inserted = 0;
  let skipped = 0;
  for (const doc of docs) {
    try {
      await Character.create(doc);
      inserted++;
    } catch (err) {
      if (err.code === 11000) {
        // 重复键错误：该字符已存在于其他级别
        skipped++;
      } else {
        console.error(`[Seed-L${level}] 插入失败 "${doc.character}":`, err.message);
      }
    }
  }

  console.log(`[Seed-L${level}] ✅ 导入完成: ${inserted} 个新字, ${skipped} 个重复(跳过)`);
  return inserted;
}

async function main() {
  try {
    await mongoose.connect(config.mongodb.uri);
    console.log('[Seed-L345] MongoDB 已连接');

    // 解析命令行参数
    const args = process.argv.slice(2);
    let levels = [3, 4, 5]; // 默认导入L3/L4/L5

    if (args.includes('--level')) {
      const idx = args.indexOf('--level');
      const level = parseInt(args[idx + 1], 10);
      if ([3, 4, 5].includes(level)) {
        levels = [level];
      } else {
        console.error('❌ --level 参数必须为 3, 4, 或 5');
        process.exit(1);
      }
    }

    // 打印当前DB状态
    const beforeCounts = {};
    for (let l = 1; l <= 5; l++) {
      beforeCounts[l] = await Character.countDocuments({ level: l });
    }
    console.log(`[Seed-L345] 当前DB字数: L1=${beforeCounts[1]}, L2=${beforeCounts[2]}, L3=${beforeCounts[3]}, L4=${beforeCounts[4]}, L5=${beforeCounts[5]}`);

    // 执行导入
    let totalInserted = 0;
    for (const level of levels) {
      const count = await seedLevel(level);
      totalInserted += count;
    }

    // 打印导入后DB状态
    const afterCounts = {};
    for (let l = 1; l <= 5; l++) {
      afterCounts[l] = await Character.countDocuments({ level: l });
    }
    console.log(`[Seed-L345] 导入后DB字数: L1=${afterCounts[1]}, L2=${afterCounts[2]}, L3=${afterCounts[3]}, L4=${afterCounts[4]}, L5=${afterCounts[5]}`);
    console.log(`[Seed-L345] ✅ 本次共导入 ${totalInserted} 个新字`);

    // 数据完整性校验
    const totalChars = await Character.countDocuments({});
    console.log(`[Seed-L345] DB总字数: ${totalChars} (预期约 301+85+380+283+218=1267, 考虑去重后约1250)`);

  } catch (err) {
    console.error('[Seed-L345] ❌ 错误:', err);
  } finally {
    await mongoose.disconnect();
    console.log('[Seed-L345] MongoDB 已断开');
  }
}

