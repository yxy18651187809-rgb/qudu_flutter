/**
 * 自动生成 Unicode 编码
 */
function generateUnicode(char) {
  const code = char.charCodeAt(0);
  return 'U+' + code.toString(16).toUpperCase().padStart(4, '0');
}

/**
 * 从拼音提取声调 (1-5, 5=轻声)
 * 拼音中的声调标记: āáǎà → 1-4, ēéěè → 1-4, īíǐì → 1-4, ōóǒò → 1-4, ūúǔù → 1-4, ǖǘǚǜ → 1-4
 */
function extractTone(pinyin) {
  if (!pinyin) return 5;
  const toneMap = {
    // 一声
    'ā': 1, 'ē': 1, 'ī': 1, 'ō': 1, 'ū': 1, 'ǖ': 1,
    // 二声
    'á': 2, 'é': 2, 'í': 2, 'ó': 2, 'ú': 2, 'ǘ': 2,
    // 三声
    'ǎ': 3, 'ě': 3, 'ǐ': 3, 'ǒ': 3, 'ǔ': 3, 'ǚ': 3,
    // 四声
    'à': 4, 'è': 4, 'ì': 4, 'ò': 4, 'ù': 4, 'ǜ': 4
  };
  for (const ch of pinyin) {
    if (toneMap[ch]) return toneMap[ch];
  }
  return 5; // 轻声
}

/**
 * 去除拼音声调符号（用于存储纯拼音）
 */
function stripTone(pinyin) {
  if (!pinyin) return '';
  return pinyin
    .replace(/[āà]/g, 'a').replace(/[āáǎà]/g, 'a')
    .replace(/[ēéěè]/g, 'e')
    .replace(/[īíǐì]/g, 'i')
    .replace(/[ōóǒò]/g, 'o')
    .replace(/[ūúǔù]/g, 'u')
    .replace(/[ǖǘǚǜ]/g, 'v');
}

